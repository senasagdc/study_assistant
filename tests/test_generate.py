import json
import sqlite3
import sys
import tempfile
import types
import unittest
from contextlib import closing
from pathlib import Path
from unittest.mock import Mock, patch

import pymupdf

from study_tool.generate import build_prompt, parse_questions, run_generation


def sample_question(identifier="q1", text="Which option?"):
    return dict(id=identifier, type="mcq", question=text,
                options=dict(A="One", B="Two", C="Three", D="Four"),
                correct_answer="A", explanation="Demo.", topic="Demo", source_pages=[1])


class GenerateTests(unittest.TestCase):
    """Gerçek Gemini yerine sahte core.llm modülü kullanılır; API çağrısı yapılmaz."""

    def setUp(self):
        self.folder = tempfile.TemporaryDirectory()
        self.addCleanup(self.folder.cleanup)
        root = Path(self.folder.name)
        self.pdf = root / "demo.pdf"
        self.extracted = root / "demo.json"
        self.bank = root / "demo_ch1_questions.json"
        self.db_path = root / "test.db"
        with pymupdf.open() as document:
            page = document.new_page()
            page.insert_text((72, 72), "Demo chapter")
            document.save(self.pdf)
        self.extracted.write_text(json.dumps(dict(source="demo.pdf", chapters=[dict(
            chapter=1, pages=[dict(page=1, text="Demo chapter")])])), encoding="utf-8")

    def fake_llm(self, questions):
        module = types.ModuleType("core.llm")
        module.MODEL = "test-model"
        module.generate_text = Mock(return_value=json.dumps(questions))
        return module

    def run_with(self, module):
        with patch.dict(sys.modules, {"core.llm": module}):
            return run_generation(self.extracted, 1, 2, db_path=self.db_path)

    def rows(self, sql):
        with closing(sqlite3.connect(self.db_path)) as connection:
            return connection.execute(sql).fetchall()

    def test_new_questions_saved_to_json_and_sqlite_as_llm(self):
        self.bank.write_text(json.dumps([sample_question()]), encoding="utf-8")
        llm = self.fake_llm([sample_question("m1", "Second?"),
                             sample_question("m2", " which OPTION? ")])
        report = self.run_with(llm)
        self.assertEqual((report["added"], report["duplicate"]), (1, 1))

        bank = json.loads(self.bank.read_text(encoding="utf-8"))
        self.assertEqual(len(bank), 2)
        self.assertEqual(bank[0], sample_question())
        new_id = bank[1]["id"]

        self.assertEqual(self.rows("SELECT kind, model FROM generations ORDER BY id"),
                         [("import", None), ("llm", "test-model")])
        self.assertEqual(
            self.rows("SELECT q.original_id, g.kind, v.change_reason FROM bank_questions q "
                      "JOIN generations g ON g.id = q.generation_id "
                      "JOIN question_versions v ON v.question_id = q.id ORDER BY q.id"),
            [("q1", "import", "Initial JSON import"), (new_id, "llm", "Generated by LLM")])
        stored = json.loads(self.rows("SELECT question_json FROM question_versions WHERE id = 2")[0][0])
        self.assertEqual(stored, bank[1])

        # Yalnızca tekrar soru dönerse yeni generation açılmaz.
        again = self.run_with(self.fake_llm([sample_question("m3", "Second?")]))
        self.assertEqual(again["added"], 0)
        self.assertEqual(self.rows("SELECT COUNT(*) FROM generations")[0][0], 2)
        self.assertEqual(self.rows("SELECT COUNT(*) FROM bank_questions")[0][0], 2)

    def test_first_generation_without_bank(self):
        self.run_with(self.fake_llm([sample_question("m1", "First?")]))
        self.assertEqual(self.rows("SELECT kind FROM generations"), [("llm",)])
        self.assertEqual(len(json.loads(self.bank.read_text(encoding="utf-8"))), 1)

    def test_pdf_mismatch_stops_before_api_and_database(self):
        self.extracted.write_text(self.extracted.read_text().replace("Demo chapter", "Wrong"))
        llm = self.fake_llm([sample_question("m1", "Second?")])
        with self.assertRaisesRegex(ValueError, "eşleşmiyor"):
            self.run_with(llm)
        llm.generate_text.assert_not_called()
        self.assertFalse(self.db_path.exists())
        self.assertFalse(self.bank.exists())

    def test_prompt_lists_existing_questions(self):
        pages = [dict(page=1, text="Demo chapter")]
        prompt = build_prompt(pages, 3, [sample_question()])
        self.assertIn("- [Demo] Which option?", prompt)
        self.assertNotIn("{EXISTING_QUESTIONS}", prompt)
        self.assertIn("None yet.", build_prompt(pages, 3, []))

        self.bank.write_text(json.dumps([sample_question()]), encoding="utf-8")
        llm = self.fake_llm([sample_question("m1", "Second?")])
        self.run_with(llm)
        self.assertIn("- [Demo] Which option?", llm.generate_text.call_args.args[0])

    def test_single_backslash_latex_is_repaired_or_rejected(self):
        raw = r'[{"explanation": "$\Phi(1.5)$ ve $\\mu$ \"x\""}]'
        self.assertEqual(parse_questions(raw)[0]["explanation"], '$\\Phi(1.5)$ ve $\\mu$ "x"')

        # "\times" tek ters bölüyle gelirse JSON onu TAB + "imes" yapar; soru reddedilir.
        broken = dict(sample_question("m1", "Second?"), explanation="$2 \times 4$")
        report = self.run_with(self.fake_llm([broken]))
        self.assertEqual((report["added"], report["invalid"]), (0, 1))
        self.assertFalse(self.bank.exists())


if __name__ == "__main__":
    unittest.main()
